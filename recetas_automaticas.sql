-- Automatización de recetas para Solo Carnes.
-- Ejecutar una vez en Supabase SQL Editor.
BEGIN;

CREATE TABLE IF NOT EXISTS public.recetas_detalle (
  receta_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  plato_id integer NOT NULL REFERENCES public.productos(producto_id) ON DELETE RESTRICT,
  insumo_id integer NOT NULL REFERENCES public.productos(producto_id) ON DELETE RESTRICT,
  cantidad numeric(14,3) NOT NULL CHECK (cantidad > 0),
  creado_en timestamptz NOT NULL DEFAULT now(),
  UNIQUE (plato_id, insumo_id),
  CHECK (plato_id <> insumo_id)
);

CREATE OR REPLACE FUNCTION public.validar_receta_detalle() RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$
DECLARE tipo_plato text; tipo_insumo text;
BEGIN
  SELECT tipo INTO tipo_plato FROM public.productos WHERE producto_id=NEW.plato_id;
  SELECT tipo INTO tipo_insumo FROM public.productos WHERE producto_id=NEW.insumo_id;
  IF tipo_plato IS DISTINCT FROM 'PLATO' THEN RAISE EXCEPTION 'El producto principal de una receta debe ser un PLATO'; END IF;
  IF tipo_insumo IS DISTINCT FROM 'INSUMO' THEN RAISE EXCEPTION 'Una receta solo puede usar INSUMOS'; END IF;
  RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS validar_receta_detalle ON public.recetas_detalle;
CREATE TRIGGER validar_receta_detalle BEFORE INSERT OR UPDATE ON public.recetas_detalle FOR EACH ROW EXECUTE FUNCTION public.validar_receta_detalle();

ALTER TABLE public.recetas_detalle ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS recetas_lectura ON public.recetas_detalle;
DROP POLICY IF EXISTS recetas_gestion ON public.recetas_detalle;
CREATE POLICY recetas_lectura ON public.recetas_detalle FOR SELECT TO authenticated USING (coalesce(public.mi_rol(),'') IN ('administrador','almacen','vendedor'));
CREATE POLICY recetas_gestion ON public.recetas_detalle FOR ALL TO authenticated USING (coalesce(public.mi_rol(),'') IN ('administrador','almacen')) WITH CHECK (coalesce(public.mi_rol(),'') IN ('administrador','almacen'));

CREATE OR REPLACE FUNCTION public.registrar_venta(p_producto_id integer,p_cantidad numeric,p_cliente_nombre text DEFAULT 'Consumidor final') RETURNS integer LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$
DECLARE p public.productos%ROWTYPE; ing public.productos%ROWTYPE; r record; nuevo numeric; resultado integer;
BEGIN
 IF coalesce(public.mi_rol(),'') NOT IN ('administrador','vendedor') THEN RAISE EXCEPTION 'Sin permiso para registrar ventas'; END IF;
 IF p_cantidad IS NULL OR NOT(p_cantidad>0 AND p_cantidad<1000000000) OR p_cantidad<>round(p_cantidad,3) THEN RAISE EXCEPTION 'Cantidad invalida'; END IF;
 SELECT * INTO p FROM public.productos WHERE producto_id=p_producto_id FOR UPDATE;
 IF NOT FOUND THEN RAISE EXCEPTION 'Producto inexistente'; END IF;
 IF p.tipo='INSUMO' THEN RAISE EXCEPTION 'Un insumo es de cocina y no se vende directamente; selecciona un plato o producto para reventa'; END IF;
 IF p.unidad='UNIDAD' AND p_cantidad<>trunc(p_cantidad) THEN RAISE EXCEPTION 'La cantidad debe ser un numero entero para UNIDAD'; END IF;
 IF p.tipo='PRODUCTO' AND p.stock<p_cantidad THEN RAISE EXCEPTION 'Stock insuficiente: disponible % %',p.stock,p.unidad; END IF;
 IF p.tipo='PLATO' AND NOT EXISTS(SELECT 1 FROM public.recetas_detalle WHERE plato_id=p_producto_id) THEN RAISE EXCEPTION 'El plato no tiene receta configurada; agrega sus insumos antes de venderlo'; END IF;
 FOR r IN SELECT * FROM public.recetas_detalle WHERE plato_id=p_producto_id ORDER BY insumo_id LOOP
   SELECT * INTO ing FROM public.productos WHERE producto_id=r.insumo_id FOR UPDATE;
   IF ing.stock < r.cantidad*p_cantidad THEN RAISE EXCEPTION 'Stock insuficiente de %: disponible % %',ing.nombre,ing.stock,ing.unidad; END IF;
 END LOOP;
 INSERT INTO public.ventas(producto_id,usuario_id,cliente_nombre,cantidad,precio_unitario,unidad) VALUES(p_producto_id,auth.uid(),coalesce(nullif(btrim(p_cliente_nombre),''),'Consumidor final'),p_cantidad,p.precio_venta,p.unidad) RETURNING venta_id INTO resultado;
 IF p.tipo='PRODUCTO' THEN
   nuevo:=p.stock-p_cantidad; UPDATE public.productos SET stock=nuevo WHERE producto_id=p_producto_id;
   INSERT INTO public.movimientos_inventario(producto_id,usuario_id,venta_id,tipo_movimiento,cantidad,stock_anterior,stock_nuevo,observacion,unidad) VALUES(p_producto_id,auth.uid(),resultado,'SALIDA',p_cantidad,p.stock,nuevo,'Venta de producto para reventa',p.unidad);
 ELSE
   FOR r IN SELECT * FROM public.recetas_detalle WHERE plato_id=p_producto_id ORDER BY insumo_id LOOP
     SELECT * INTO ing FROM public.productos WHERE producto_id=r.insumo_id FOR UPDATE; nuevo:=ing.stock-r.cantidad*p_cantidad;
     UPDATE public.productos SET stock=nuevo WHERE producto_id=ing.producto_id;
     INSERT INTO public.movimientos_inventario(producto_id,usuario_id,venta_id,tipo_movimiento,cantidad,stock_anterior,stock_nuevo,observacion,unidad) VALUES(ing.producto_id,auth.uid(),resultado,'SALIDA',r.cantidad*p_cantidad,ing.stock,nuevo,'Receta automática: '||p.nombre,ing.unidad);
   END LOOP;
 END IF;
 RETURN resultado;
END $$;
GRANT SELECT,INSERT,UPDATE,DELETE ON public.recetas_detalle TO authenticated;
GRANT USAGE,SELECT ON SEQUENCE public.recetas_detalle_receta_id_seq TO authenticated;
GRANT EXECUTE ON FUNCTION public.registrar_venta(integer,numeric,text) TO authenticated;
COMMIT;
